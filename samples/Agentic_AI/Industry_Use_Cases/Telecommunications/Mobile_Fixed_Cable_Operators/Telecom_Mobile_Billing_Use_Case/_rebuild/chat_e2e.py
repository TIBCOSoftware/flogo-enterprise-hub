        check("DB: roaming effects match the events (TravelPass enrolled / roaming limit set)",
              all((x["action_type"] == "ADD_TRAVEL_PASS" and cust(MARIA, "travel_pass_since") != "")
                  or (x["action_type"] == "SET_ROAMING_LIMIT" and cust(MARIA, "roaming_limit") != "") for x in roam_ev))
