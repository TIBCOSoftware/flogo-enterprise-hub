ANSI = re.compile(r"\x1b\[[0-9;]*m")
AGENT_MARKERS = {a: r"starting agent execution\s+agent=" + a + r"\b" for a in ("fault_triage_agent", "repeat_defect_agent", "shift_handover_agent")}
