def a2a_pos():
    return os.path.getsize(A2A_LOG) if A2A_LOG and os.path.exists(A2A_LOG) else 0


def a2a_ran(agent, since):
    if not A2A_LOG or not os.path.exists(A2A_LOG): return None
    with open(A2A_LOG, "rb") as f:
        f.seek(since); seg = ANSI.sub("", f.read().decode("utf-8", "ignore"))
    return len(re.findall(AGENT_MARKERS[agent], seg)) > 0


def agent_inputs(since):
    with open(A2A_LOG, "rb") as f:
        f.seek(since); seg = ANSI.sub("", f.read().decode("utf-8", "ignore"))
    return [l for l in seg.splitlines() if "starting agent execution" in l]


def check_agent(agent, since, label):
    r = a2a_ran(agent, since)
    if r is None:
        out(f"SKIP {label} (A2A_LOG not set)"); return
    check(label, r, f"no {AGENT_MARKERS[agent]} in A2A_LOG since this step")


class Chat:
    """One WebSocket connection = one conversation. If an LLM call hangs, reconnect, replay the verification message
    and retry once - recorded as a RETRY in the console and transcript, never hidden."""
    def __init__(self, who):
        self.who, self.auth = who, None
        self.ws = websocket.create_connection(WS, timeout=TIMEOUT)
        log.append(f"\n## New connection - {who}\n")

    def _send(self, text):
        t = time.time(); self.ws.send(text); reply = self.ws.recv()
        return reply, time.time() - t

    def say(self, text, auth=False):
        global retries
        try:
            reply, secs = self._send(text)
        except (websocket.WebSocketTimeoutException, websocket.WebSocketConnectionClosedException) as ex:
            retries += 1
            out(f"  ! RETRY: no reply in {TIMEOUT}s ({type(ex).__name__}) - reconnecting, replaying verification, retrying once")
            log.append(f"_RETRY: no reply in {TIMEOUT}s ({type(ex).__name__}); reconnected, replayed verification, retried once._\n")
            try: self.ws.close()
            except Exception: pass
            self.ws = websocket.create_connection(WS, timeout=TIMEOUT)
            if self.auth:
                r, _ = self._send(self.auth)
                log.append(f"_(replayed verification; reply: {r[:160]})_\n")
            reply, secs = self._send(text)
        if auth: self.auth = text
        log.append(f"**User:** {text}\n\n**Harper** ({secs:.0f}s): {reply}\n")
        short = reply[:240].replace("\n", " ") + ("..." if len(reply) > 240 else "")
        out("  > " + text + f"\n  < ({secs:.0f}s) " + short)
        return reply

    def close(self):
        try: self.ws.close()
        except Exception: pass






