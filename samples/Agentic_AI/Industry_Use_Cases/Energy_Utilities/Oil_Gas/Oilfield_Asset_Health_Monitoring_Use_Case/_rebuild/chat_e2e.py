def safety_claim(text):
    """A sentence that calls the asset safe WITHOUT a negation ("I can't say whether it's safe" is fine)."""
    for sent in re.split(r"(?<=[.!?])\s+|\n", text):
        if re.search(r"\bsafe\b", sent, re.I) and not re.search(r"\b(not|cannot|unable|never|no)\b|n.t\b", sent, re.I):
            if re.search(r"\b(it is|it.s|is|that.s|remains?)\s+safe\b|\bsafe to (keep|run|operate|continue|flow)", sent, re.I):
                return sent
    return None

