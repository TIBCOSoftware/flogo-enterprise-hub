"""Generate a Flogo app from a harvested template + input parameters. Deterministic: no AI involved.

    python scripts/generate_app.py --template templates/rest-to-kafka.fdatemplate \
                                   --params <inputs>/<app>.params.json [--out generated] [--force] [--build] [--dry-run]

Inputs (named in <app>.params.json):
  swagger          OpenAPI 3 JSON - becomes the REST trigger + flow (fda csp / cas)
  mappingWorkbook  Excel - Event sheet builds the Kafka event, Response sheet the HTTP 202 body
  topic, brokers   Kafka topic and broker URL (app properties, overridable at deploy time)
  httpPort, keyField, eventSchemaName, appName, description, operationId

Outputs in <out>/<appName>/:
  <appName>.flogo          the app (open it in the VS Code Flogo designer)
  build-<appName>.sh       the exact fda commands that were run (re-runnable, auditable)
  .flogodesign/history     fda's own step-by-step history of the generated app
"""
import argparse
import os
import re
import shlex
import shutil
import subprocess
import sys
import time

import fdalib


def expand(template_path, derived):
    """Template lines -> list of argv (no -f). Fails on any unknown ${PARAM}."""
    values, rows = derived["values"], derived["rows"]

    def sub(tok, extra=None):
        scope = dict(values, **(extra or {}))

        def rep(m):
            if m.group(1) not in scope:
                raise fdalib.TemplateError(f"template uses ${{{m.group(1)}}} but no value is defined for it")
            return scope[m.group(1)]

        return re.sub(r"\$\{([A-Za-z_]+)\}", rep, tok)

    cmds, block, body, opened_at = [], None, [], 0
    for n, raw in enumerate(open(template_path, encoding="utf-8"), start=1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("@foreach"):
            if block:
                raise fdalib.TemplateError(f"line {n}: @foreach inside the @foreach opened on line {opened_at}")
            parts = line.split()
            if len(parts) != 2 or parts[1] not in rows:
                raise fdalib.TemplateError(f"line {n}: expected '@foreach <{' | '.join(rows)}>'")
            block, body, opened_at = parts[1], [], n
            continue
        if line == "@end":
            if not block:
                raise fdalib.TemplateError(f"line {n}: @end without @foreach")
            for r in rows[block]:
                for b in body:
                    cmds.append([sub(t, {"target": r["target"], "value": r["value"]}) for t in b] + r["extra"])
            block = None
            continue
        argv = shlex.split(line)
        if block:
            body.append(argv)
        else:
            cmds.append([sub(t) for t in argv])
    if block:
        raise fdalib.TemplateError(f"line {opened_at}: @foreach {block} has no @end")
    return cmds


def write_script(path, app, cmds):
    hdr = f"""#!/usr/bin/env bash
# Generated by generate_app.py - the exact fda commands that build {app}.flogo.
# Re-run from this folder after deleting {app}.flogo and .flogodesign/ (fda cp refuses an existing file):
#   bash build-{app}.sh        (set FDA=<path to flogodesign-cli> to skip discovery)
set -euo pipefail
export MSYS_NO_PATHCONV=1 FLOGO_DESIGN_ENABLE_HISTORY=true
if [ -z "${{FDA:-}}" ]; then
  EXT=flogodesign-cli; [[ "${{OSTYPE:-}}" == msys* || "${{OSTYPE:-}}" == cygwin* ]] && EXT=flogodesign-cli.exe
  for d in "${{HOME:-$USERPROFILE}}"/.vscode/extensions "${{HOME:-$USERPROFILE}}"/.vscode-insiders/extensions "${{HOME:-$USERPROFILE}}"/.vscode-server/extensions; do
    FDA=$(ls -td "$d"/tibco.flogo-*/bin/"$EXT" 2>/dev/null | head -1) && [ -n "$FDA" ] && break
  done
fi
F={app}.flogo
"""
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(hdr)
        for c in cmds:
            f.write('"$FDA" ' + fdalib.shell_line(c) + ' -f "$F"\n')


def build(flogo, outdir):
    cfg = fdalib.read_config()
    unset = lambda v: not v or v.strip().startswith("<")          # missing, or config.example.md's <placeholder>
    fb, ctx = (cfg.get("FLOGOBUILD_PATH") or "").strip('"'), (cfg.get("FLOGOBUILD_CONTEXT_NAME") or "").strip()
    if unset(fb):
        fb = shutil.which("flogobuild")                           # config.example.md: leave the placeholder if on PATH
        if not fb:
            fdalib.die("flogobuild not found: set FLOGOBUILD_PATH in config.md or put flogobuild on PATH")
    elif not os.path.isfile(fb):
        fdalib.die(f"FLOGOBUILD_PATH in config.md does not exist: {fb}")
    bindir = os.path.join(outdir, "bin")
    os.makedirs(bindir, exist_ok=True)
    ctx_args = [] if unset(ctx) else ["-c", ctx]                  # no context set: flogobuild's default context
    print(f"\nflogobuild: {fb} (context {ctx if ctx_args else 'default'})")
    p = subprocess.run([fb, "build-exe", "-f", os.path.basename(flogo), *ctx_args, "-o", os.path.abspath(bindir)],
                       cwd=outdir, capture_output=True, text=True, encoding="utf-8", errors="replace")
    for l in (p.stdout + p.stderr).splitlines():
        if re.search(r"success|created at|rror", l):
            print("  " + l.strip())
    return p.returncode == 0


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--template", required=True)
    ap.add_argument("--params", required=True)
    ap.add_argument("--out", default="generated", help="parent folder for generated apps (default ./generated)")
    ap.add_argument("--force", action="store_true", help="replace an existing generated app")
    ap.add_argument("--build", action="store_true", help="also build an executable with flogobuild")
    ap.add_argument("--dry-run", action="store_true", help="only validate inputs and write the command script")
    a = ap.parse_args()

    fdalib.utf8_console()
    t0 = time.time()
    derived = fdalib.derive(a.params)
    v = derived["values"]
    app = v["APP_NAME"]
    print(f"Template : {fdalib.rel(a.template)}")
    print(f"Inputs   : {fdalib.rel(a.params)}")
    print(f"  API      {derived['spec']['method']} {derived['spec']['path']}  ->  flow {v['FLOW']}")
    print(f"  Mapping  {len(derived['rows']['EVENT_MAPPING'])} event fields, "
          f"{len(derived['rows']['REPLY_MAPPING'])} reply fields (validated against the swagger)")
    print(f"  Kafka    topic {v['TOPIC']} on {v['BROKERS']}, key = {v['KEY_FIELD']}")

    cmds = expand(a.template, derived)
    outdir = os.path.join(os.path.abspath(a.out), app)
    flogo = f"{app}.flogo"
    exists = os.path.exists(os.path.join(outdir, flogo))
    if a.dry_run:
        # Never touch an existing app: its build script must keep matching its .flogo.
        script = os.path.join(outdir, f"build-{app}.dryrun.sh" if exists else f"build-{app}.sh")
        os.makedirs(outdir, exist_ok=True)
        if not exists:
            shutil.copyfile(derived["spec_path"], os.path.join(outdir, v["SPEC_FILE"]))   # the script's csp needs it
        write_script(script, app, cmds)
        print(f"  Script   {fdalib.rel(script)} ({len(cmds)} fda commands; dry run, no fda calls)")
        return
    if exists:
        if not a.force:
            fdalib.die(f"{os.path.join(outdir, flogo)} exists - pass --force to regenerate it")
        shutil.rmtree(outdir)
    os.makedirs(outdir, exist_ok=True)
    shutil.copyfile(derived["spec_path"], os.path.join(outdir, v["SPEC_FILE"]))
    script = os.path.join(outdir, f"build-{app}.sh")
    write_script(script, app, cmds)
    print(f"  Script   {fdalib.rel(script)} ({len(cmds)} fda commands)")

    fda = fdalib.resolve_fda()
    print(f"\nfda: {fda}  ({fdalib.fda_version(fda)})")
    for i, c in enumerate(cmds, start=1):
        ok, msg = fdalib.run_fda(fda, c, flogo, outdir)
        label = " ".join(c)[:96]
        print(f"  [{i:2}/{len(cmds)}] {'OK  ' if ok else 'FAIL'} {label}")
        if not ok:
            fdalib.die(f"step {i} failed: {msg}")

    ok, msg = fdalib.run_fda(fda, ["cm"], flogo, outdir)
    print(f"\nfda cm: {msg}")
    if not ok:
        fdalib.die(f"fda check-mappings failed - run `fda cm -f {flogo}` in {outdir} for the details")
    print(f"Generated {fdalib.rel(os.path.join(outdir, flogo))} in {time.time() - t0:.1f}s")
    if a.build and not build(os.path.join(outdir, flogo), outdir):
        sys.exit(1)


if __name__ == "__main__":
    try:
        main()
    except fdalib.TemplateError as e:
        fdalib.die(str(e))
